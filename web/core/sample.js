// お試し用のサンプルデータ（書名・著者・文章はすべて架空。実在の本からの引用ではありません）
// 「サンプルで試す」ボタンと、分析パイプラインのテストで使う。

const book = (title, author, source, chapters) => {
  let loc = 100;
  let day = 1;
  const highlights = [];
  for (const [chapter, items] of chapters) {
    for (const item of items) {
      const [text, note] = Array.isArray(item) ? item : [item, ''];
      loc += 37 + (text.length % 50);
      day += 1;
      highlights.push({
        text,
        note,
        chapter,
        ...(source === 'kindle' ? { location: loc, locationEnd: loc + 2 } : { page: String(Math.round(loc / 12)) }),
        color: ['yellow', 'blue', 'yellow', 'green'][highlights.length % 4],
        createdAt: new Date(Date.UTC(2025, (title.length + day) % 12, 1 + (day % 27), 12)).toISOString(),
      });
    }
  }
  return { title, author, source, highlights };
};

